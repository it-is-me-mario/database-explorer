def serialise(value):
    if isinstance(value,np.ndarray):return value.tolist()
    if isinstance(value,dict):return {k:serialise(v) for k,v in value.items()}
    if isinstance(value,(list,tuple)):return [serialise(v) for v in value]
    return value

def write(path,value):
    path.parent.mkdir(parents=True,exist_ok=True);temporary=path.with_suffix('.tmp')
    temporary.write_text(json.dumps(serialise(value),ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n');temporary.replace(path)

def collect(identifier,path,*,native_cache=None):
    start=time.monotonic();seed=ROOT/'doc/source/_static/data/economy'/(identifier+'.json')
    if not seed.exists():raise ValueError('No reviewed production recipe: '+identifier)
    original=json.loads(seed.read_text());recipe=original['recipe']
    if not path.exists():raise FileNotFoundError(path.name)
    if native_cache:
        metadata=json.loads((native_cache/'metadata.json').read_text());arrays=np.load(native_cache/'native.npz');native={**metadata,**{k:arrays[k] for k in arrays.files}}
        if metadata['recipe']!=recipe:raise ValueError('Private cache recipe differs')
    else:
        db=load_database(recipe,path);native=from_database(db,recipe);del db;gc.collect()
    import mario
    if mario.__version__!='1.3.4':raise RuntimeError('Use the pinned mariopy==1.3.4 runtime')
    labels=list(dict.fromkeys(native['producer_regions']))
    native_income=np.bincount([labels.index(x) for x in native['producer_regions']],weights=native['va'],minlength=len(labels))*recipe['currency_scale']
    previous={r['code']:sum(r['value_added']) for r in original['regions']}
    if not np.allclose(native_income,[previous[c] for c in labels],rtol=1e-9,atol=.1):
        raise ValueError('Local source income differs from the production snapshot; explicitly refresh and reconcile that source vintage before publishing accounts')
    flows=regional_flows(native);solved=regional_multipliers(native);labels=solved['labels']
    values={'gross_output':gross_output.compute(native),'domestic_use':domestic_use.compute(native,flows),'final_demand':final_demand.compute(native),'value_added_footprint':value_added_footprint.compute(native,solved,flows)['values']}
    residuals={'value_added':solved['unallocated_va']*recipe['currency_scale']}
    carbon=None
    if native.get('ghg') is not None:
        footprint=ghg_footprint.compute(native,solved,flows);values['ghg_footprint']=footprint['values'];residuals['ghg_tonnes']=footprint['unallocated'];carbon=ghg_trade.compute(native,solved,flows)
    rows=[]
    geography={r['label']:r for r in recipe['regions']}
    for i,label in enumerate(labels):
        row={**geography[label],'code':label,'accounts':{}}
        for metric,value in values.items():
            row['accounts'][metric]={k:v[i] for k,v in value.items()} if isinstance(value,dict) else value[i] if metric!='gross_output' else np.array([value[i]])
        rows.append(row)
    notes={k:NOTES[k] for k in values}
    if carbon is not None:notes['ghg_trade']=NOTES['ghg_trade']
    if 'ghg_tonnes' in residuals:
        residual=float(residuals['ghg_tonnes'].sum());total=float(native['ghg'].sum());notes['ghg_footprint']+=f' Unallocated production emissions: {residual:,.3f} t CO2eq globally ({100*residual/total:.6f}% of the reviewed production total); kept by production origin, with no consumer allocation.'
    for metric in ('ghg_footprint','ghg_trade'):
        if metric in notes:notes[metric]+=' '+recipe.get('ghg_note','')
    if carbon is not None:notes['ghg_trade']+=f' Unallocated zero-output production GHG: {float(residuals["ghg_tonnes"].sum()):,.3f} t CO2eq globally.'
    data={'schema_version':1,'id':identifier,'recipe':recipe,'regions':rows,'metrics':list(values),'components':{k:LABELS[k] for k in values},'notes':notes,'residuals':residuals,'ghg_trade':carbon,
        'provenance':{'mario_version':'1.3.4','recipe_modules':'_static/reproduce/recipes','linear_residual':solved['relative_residual'],'native_country_scope_complete':True,'generated_at':datetime.now(timezone.utc).isoformat(),'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None}}
    write(OUTPUT/(identifier+'.json'),data);rebuild_manifest()
    print('PASSED',identifier,'metrics',list(values)+(['ghg_trade'] if carbon is not None else []),'solve residual',solved['relative_residual'],'seconds',round(time.monotonic()-start,2),flush=True)
    return data

def rebuild_manifest():
    records=[]
    for path in sorted(OUTPUT.glob('*.json')):
        if path.name=='manifest.json':continue
        data=json.loads(path.read_text());records.append({'id':data['id'],'file':path.name,'metrics':data['metrics']+(['ghg_trade'] if data.get('ghg_trade') else [])})
    write(OUTPUT/'manifest.json',{'schema_version':1,'readings':records})

