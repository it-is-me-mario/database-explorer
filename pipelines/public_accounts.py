COMPONENTS={'gross_output':['Total'],'domestic_use':['Domestic'],'final_demand':['Domestic','Imported'],'value_added_footprint':['Domestic value added','Foreign value added'],'ghg_footprint':['Domestic emissions','Foreign emissions']}
NOTES={
'gross_output':'Native MARIO X for IOTs and Xc for SUTs, summed over producing nodes. Gross output includes intermediate production at multiple stages and is not GDP.',
'domestic_use':'Domestic-origin use within the same native region only: matching origin and destination regions in Z and Y (IOT) or U and Yc (SUT). Intermediate and final uses enter once; signed source adjustments are retained.',
'final_demand':'Final demand by consumer region from Y (IOT) or Yc (SUT). Domestic and Imported identify the supplying row region relative to that consumer. A shared SNA category vocabulary is used; native combined categories are never split or duplicated.',
'value_added_footprint':'Reviewed value added generated by domestic and foreign producers to meet final demand in the selected consumer region. Native direct coefficients retain production origins before MARIO calc_m_from_z solves the system. Multiplication by Y/Yc retains final-consumer columns; no full inverse is constructed.',
'ghg_footprint':'Allocable GHG supported by final demand in the consumer region, plus supplied direct final-user emissions once. MARIO calc_ghg uses the reviewed source characterisation, and calc_f_from_z retains production origins before multiplying by Y/Yc. Direct accounts and upstream requirements outside the representable final-demand boundary stay quantified by production origin.'}


def serialise(value):
    if isinstance(value,np.ndarray):return value.tolist()
    if isinstance(value,dict):return {k:serialise(v) for k,v in value.items()}
    if isinstance(value,(tuple,list)):return [serialise(v) for v in value]
    return value


def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True);temporary=path.with_suffix('.'+uuid.uuid4().hex+'.tmp')
    temporary.write_text(json.dumps(serialise(data),ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n');temporary.replace(path)


def rebuild_manifest():
    lock=ROOT/'_cache/accounts-manifest.lock';lock.parent.mkdir(parents=True,exist_ok=True)
    with lock.open('a') as stream:
        fcntl.flock(stream,fcntl.LOCK_EX);records=[]
        for path in sorted(OUTPUT.glob('*.json')):
            if path.name=='manifest.json':continue
            data=json.loads(path.read_text());records.append({'id':data['id'],'file':path.name,'metrics':data['metrics']+(['ghg_trade'] if data.get('ghg_trade') else []),'demand_groups':list(data.get('demand_groups',{}))})
        write(OUTPUT/'manifest.json',{'schema_version':1,'readings':records})


def publish(job,values,*,groups=None,residuals=None,details=None):
    identifier=job['id'];recipe=copy.deepcopy(job['original']['recipe']);
    if job['recipe'].get('footprint_compute'):recipe['footprint_compute']=copy.deepcopy(job['recipe']['footprint_compute'])
    target=OUTPUT/(identifier+'.json')
    data=json.loads(target.read_text()) if target.exists() else {'schema_version':1,'id':identifier,'recipe':recipe,'regions':[],'metrics':[],'components':{},'notes':{},'residuals':{},'ghg_trade':None,'provenance':{}}
    # A direct refresh or a failed footprint retry must retain the solver of
    # the still-published footprint values, rather than the attempted new solve.
    if not any(metric.endswith('_footprint') for metric in values) and any(metric.endswith('_footprint') for metric in data['metrics']):
        retained=data['recipe'].get('footprint_compute')
        if retained is None:recipe.pop('footprint_compute',None)
        else:recipe['footprint_compute']=copy.deepcopy(retained)
    data['recipe']=recipe
    labels=details['regions'];known={r.get('label',r.get('code')):r for r in recipe['regions']};previous={r.get('code',r.get('label')):r for r in data['regions']}
    old_labels=[r.get('code',r.get('label')) for r in data['regions']]
    if old_labels and old_labels!=labels:
        positions=[old_labels.index(label) for label in labels]
        data['residuals']={k:np.asarray(v)[positions] for k,v in data['residuals'].items()}
        for proof in data['provenance'].get('footprint_boundaries',{}).values():
            for key in ['production_by_origin','allocated_by_origin','unrepresented_direct','unassigned_requirements','direct_final_contribution']:
                if key in proof:proof[key]=np.asarray(proof[key])[positions]
    if data.get('ghg_trade'):
        trade_labels=data['provenance'].get('ghg_trade_region_order',old_labels)
        positions=[trade_labels.index(label) for label in labels]
        data['ghg_trade']={k:np.asarray(v)[np.ix_(positions,positions)] for k,v in data['ghg_trade'].items()}
        data['provenance']['ghg_trade_region_order']=labels
    rows=[]
    for i,label in enumerate(labels):
        row=previous.get(label,{**known[label],'code':label,'accounts':{}})
        for metric,value in values.items():row['accounts'][metric]={k:v[i] for k,v in value.items()} if isinstance(value,dict) else value[i]
        rows.append(row)
    data['regions']=rows;data['metrics']=list(dict.fromkeys([*data['metrics'],*values]));data['components'].update({k:COMPONENTS[k] for k in values});data['notes'].update({k:NOTES[k] for k in values})
    if 'value_added_footprint' in values and recipe.get('value_added_footprint_note'):data['notes']['value_added_footprint']+=' '+recipe['value_added_footprint_note']
    if 'final_demand' in values:
        data['notes']['final_demand']+=' '+consumption_note(recipe)
        if recipe.get('final_demand_note'):data['notes']['final_demand']+=' '+recipe['final_demand_note']
    if 'value_added_footprint' in values:
        remaining=float(np.asarray(residuals['value_added']).sum());data['notes']['value_added_footprint']+=f' Unallocated production value added: {remaining:,.3f} {recipe["currency"]} globally (signed native-currency result). Direct unrepresented production accounts and upstream requirements outside observed final demand stay by production origin.'
    if groups is not None:
        data['demand_groups']=groups
        data['demand_schema_version']=2
        data['provenance'].pop('direct_account_method',None)
    if residuals:data['residuals'].update(residuals)
    if 'ghg_footprint' in values:
        remaining=float(np.asarray(residuals['ghg_tonnes']).sum());data['notes']['ghg_footprint']+=' '+recipe.get('ghg_note','')+f' Unallocated production emissions: {remaining:,.3f} t CO2eq globally; direct unrepresented accounts and requirements outside observed final demand are retained by production origin, without a consumer allocation.'
    data['provenance'].update(mario_version='1.3.4',recipe_modules='_static/reproduce/recipes',native_country_scope_complete=True,generated_at=datetime.now(timezone.utc).isoformat())
    import mario,pandas
    data['provenance']['runtime']={'python':sys.version.split()[0],'numpy':np.__version__,'pandas':pandas.__version__,'compute':mario.download_settings()['compute']}
    data['provenance'].setdefault('footprint_boundaries',{}).update(details.get('footprint_details',{}))
    methods=data['provenance'].setdefault('metric_methods',{})
    for metric in values:
        methods[metric]='Released MARIO public APIs; native IOT/SUT blocks and region aggregation'
        if job.get('verified_inputs'):data['provenance'].setdefault('metric_inputs',{})[metric]=job['verified_inputs']
        if metric.endswith('_footprint'):
            data['provenance'].setdefault('metric_compute',{})[metric]={'method':'solve','strategy':recipe.get('footprint_compute',{}).get('strategy','direct'),'solver':recipe.get('footprint_compute',{}).get('solver',mario.download_settings()['compute']['linear_solver']),'refinement_steps':recipe.get('footprint_compute',{}).get('refinement_steps',0)}
    write(target,data);rebuild_manifest()


def collect(job,*,force_footprints=False,direct_only=False):
    identifier=job['id'];start=time.monotonic();r=job['recipe'];target=OUTPUT/(identifier+'.json')
    old=json.loads(target.read_text()) if target.exists() else {};old_methods=old.get('provenance',{}).get('metric_methods',{})
    wanted={'gross_output','domestic_use','final_demand','value_added_footprint'}
    if r.get('ghg_factors') and r.get('ghg_usable') is not False:wanted.add('ghg_footprint')
    if direct_only:wanted={'gross_output','domestic_use','final_demand'}
    if not force_footprints and {'gross_output','domestic_use','final_demand'}<=set(old_methods) and wanted<=set(old.get('metrics',[])) and old.get('demand_schema_version')==2:print('CACHED',identifier,flush=True);return
    print('START',identifier,r['table'],flush=True)
    runtime_recipe=copy.deepcopy(r)
    if direct_only:
        if r['source']=='GLORIA':runtime_recipe['parser_options']['satellites']=False
        if r['source']=='EMERGING':
            runtime_recipe['parser_options']['load_co2']=False
            runtime_recipe['parser_options'].pop('co2_path',None)
        if r['source'] in {'ADB','WIOD','EXIOBASE'}:runtime_recipe['parser_options'].pop('add_extensions',None)
        if r['parser']=='parse_figaro_e3':runtime_recipe['parser_options']['extensions']=False
    if r['source']=='EMERGING':
        from .account_jobs.emerging import verify_inputs
        job['verified_inputs']=verify_inputs(job['path'],runtime_recipe,job['original']['provenance'])
    db=load_database(runtime_recipe,job['path'])
    labels=db.get_index('Region');income=api.production_income(db,r)
    previous={row['code']:sum(row['value_added']) for row in job['original']['regions']}
    if previous and not np.allclose(income,[previous[c] for c in labels],rtol=1e-9,atol=.1):
        raise ValueError('Local source income differs from the production snapshot; explicitly audit and refresh the source vintage')
    direct=api.direct_accounts(db,r)
    labels=direct['regions'];values={k:direct[k] for k in ('gross_output','domestic_use','final_demand')}
    publish(job,values,groups=direct['demand_groups'],details=direct)
    failures=[]
    to_compute=[metric for metric in ['value_added_footprint','ghg_footprint'] if metric in wanted and (metric not in old.get('metrics',[]) or force_footprints)]
    calculated={'results':{},'errors':{}}
    if to_compute:
        api.prepare_footprint_model(db,r)
        print('COMPUTE TOGETHER',identifier,','.join(to_compute),flush=True)
        calculated=api.footprints(db,r,to_compute)
    # A missing or undefined footprint never gates the three native direct indicators.
    for metric,function in [('value_added_footprint',api.value_added_footprint),('ghg_footprint',api.ghg_footprint)]:
        if metric not in wanted:continue
        if metric in old.get('metrics',[]) and not force_footprints:continue
        print('COMPUTE',identifier,metric,flush=True)
        try:
            if metric in calculated['errors']:raise calculated['errors'][metric]
            result=calculated['results'][metric];residuals={('value_added' if metric=='value_added_footprint' else 'ghg_tonnes'):result['unallocated']}
            details={k:serialise(result[k]) for k in ['unrepresented_direct','unassigned_requirements','source_requirement_gap','production_by_origin','allocated_by_origin']}
            details['recipe_version']=2
            if metric=='ghg_footprint':details['direct_final_contribution']=serialise(result['direct_final_demand'])
            direct['footprint_details']={metric:details}
            publish(job,{metric:result['values']},residuals=residuals,details=direct)
            (ROOT/'_cache/account-errors'/(identifier+'-'+metric+'.json')).unlink(missing_ok=True)
            print('METRIC PASSED',identifier,metric,flush=True)
        except Exception as error:
            failures.append(metric)
            traceback.print_exc();write(ROOT/'_cache/account-errors'/(identifier+'-'+metric+'.json'),{'id':identifier,'metric':metric,'error':str(error),'type':type(error).__name__})
    (ROOT/'_cache/account-errors'/(identifier+'-source.json')).unlink(missing_ok=True)
    print('PASSED',identifier,'seconds',round(time.monotonic()-start,1),flush=True)
    del db;gc.collect()
    return failures


def main():
    cli=argparse.ArgumentParser(description=__doc__);cli.add_argument('--source-root',type=Path);cli.add_argument('--inventory',type=Path);cli.add_argument('--solver',choices=['scipy','umfpack'],help='Explicit projected matrix-call override; a parser may apply its own session preset');cli.add_argument('--strategy',choices=['direct','iterative'],default='direct');cli.add_argument('--refinement-steps',type=int,choices=[0,1,2],default=0);cli.add_argument('--source');cli.add_argument('--only');cli.add_argument('--force-footprints',action='store_true');cli.add_argument('--direct-only',action='store_true');cli.add_argument('--all-footprints',action='store_true',help='Include deferred footprints; default follows the current collection priority');cli.add_argument('--resume',action='store_true',help='Compatibility flag: completed readings are always cached');args=cli.parse_args()
    import mario
    if mario.__version__!='1.3.4':raise RuntimeError('Use mariopy==1.3.4')
    if args.solver:mario.set_linear_solver(args.solver)
    if args.inventory:
        items=json.loads(args.inventory.read_text());items=[{**j,'path':Path(j['path'])} for j in items]
    elif args.source_root:items=list(jobs(args.source_root))
    else:cli.error('Supply --source-root or the reviewed private --inventory')
    scope=json.loads((ROOT/'doc/account-collection-scope.json').read_text())['readings']
    priority={row['id'] for row in scope if any(metric.endswith('_footprint') for metric in row['metrics'])}
    unavailable={row['id'] for row in scope if row.get('status')=='unavailable source archive'}
    failures=[]
    for job in items:
        if args.source and job['recipe']['source'].lower()!=args.source.lower():continue
        if args.only and args.only not in job['id']:continue
        if job['id'] in unavailable:
            print('UNAVAILABLE SOURCE',job['id'],flush=True);continue
        job['recipe']['footprint_compute']={'strategy':args.strategy,'refinement_steps':args.refinement_steps}
        if args.solver:job['recipe']['footprint_compute']['solver']=args.solver
        direct_only=args.direct_only or (not args.all_footprints and job['id'] not in priority)
        try:failures.extend((job['id']+': '+metric for metric in collect(job,force_footprints=args.force_footprints,direct_only=direct_only) or []))
        except Exception as error:
            failures.append(job['id']+': source')
            traceback.print_exc();write(ROOT/'_cache/account-errors'/(job['id']+'-source.json'),{'id':job['id'],'error':str(error),'type':type(error).__name__})
        gc.collect()
    print('COLLECTION FINISHED',len(failures),'unresolved calculations',flush=True)
    if failures:raise SystemExit(1)
if __name__=='__main__':main()
